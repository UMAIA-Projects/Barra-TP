class Car {
  final int id;
  final String category;
  final String name;
  final String image;
  final double rating;
  final int seats;
  final String transmission;
  final int largeBags;
  final int smallBags;
  final int price;
  final int days;

  Car({
    required this.id,
    required this.category,
    required this.name,
    required this.image,
    required this.rating,
    required this.seats,
    required this.transmission,
    required this.largeBags,
    required this.smallBags,
    required this.price,
    required this.days,
  });
}
